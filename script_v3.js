function renderKeywords() {
  const cloud = document.getElementById("keyword-cloud");
  const placements = [
    { x: 26, y: 24 },
    { x: 70, y: 26 },
    { x: 32, y: 68 },
    { x: 74, y: 68 }
  ];

  DATA.keywords.forEach((keyword, index) => {
    const chip = document.createElement("span");
    chip.className = "keyword-chip";
    chip.textContent = keyword;
    chip.style.left = placements[index].x + "%";
    chip.style.top = placements[index].y + "%";
    chip.style.setProperty("--delay", `${index * -2.8}s`);
    cloud.appendChild(chip);
  });
}

function renderConstellation() {
  const items = DATA.publications;
  const journal = items.filter((item) => item.group === "Peer-Reviewed Journal Articles");
  const chapters = items.filter((item) => item.group === "Book Chapters");
  const rings = [
    { items: journal, radius: 26, start: -90, end: 160 },
    { items: chapters, radius: 38, start: -30, end: 250 }
  ];

  stageEl.querySelectorAll(".pub-node").forEach((node) => node.remove());
  lineEl.innerHTML = "";

  rings.forEach((ring) => {
    ring.items.forEach((item, idx) => {
      const angle = ring.items.length === 1
        ? ring.start
        : ring.start + ((ring.end - ring.start) / (ring.items.length - 1)) * idx;
      const x = Math.cos((angle * Math.PI) / 180) * ring.radius;
      const y = Math.sin((angle * Math.PI) / 180) * ring.radius;

      const btn = document.createElement("button");
      btn.type = "button";
      btn.className = "pub-node";
      btn.dataset.id = item.id;
      btn.style.setProperty("--x", `${x}%`);
      btn.style.setProperty("--y", `${y}%`);
      btn.innerHTML = `
        <span class="pub-node-year">${item.year}</span>
        <span class="pub-node-title">${item.title}</span>
      `;
      btn.addEventListener("click", () => selectPublicationById(item.id, true));
      stageEl.appendChild(btn);

      const line = document.createElementNS("http://www.w3.org/2000/svg", "line");
      line.setAttribute("x1", "50");
      line.setAttribute("y1", "50");
      line.setAttribute("x2", String(50 + x));
      line.setAttribute("y2", String(50 + y));
      lineEl.appendChild(line);
    });
  });
}

